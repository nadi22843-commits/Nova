/**
 * Модель мест.
 *
 * Главное решение: дерево произвольной глубины вместо фиксированных уровней.
 * Административное устройство стран несовместимо между собой:
 *
 *   Россия     страна → субъект → город → район
 *   США        country → state → county → city
 *   Франция    pays → région → département → commune
 *   Япония     国 → 都道府県 → 市 → 区
 *   ОАЭ        دولة → إمارة → مدينة
 *   Сингапур   страна → район (два уровня, и всё)
 *
 * Любая попытка загнать это в поля «регион» и «город» ломается на первой же
 * стране, которая устроена иначе. Поэтому уровни — просто глубина в дереве,
 * а как они называются, знает конфигурация страны.
 */

/**
 * Семантическая роль уровня. Это НЕ название для показа — название приходит
 * из levelLabels страны на нужном языке.
 *
 * admin1 — верхнее административное деление (штат, область, эмират, префектура)
 * admin2 — второе (округ, департамент, район области)
 * city   — населённый пункт
 * district — часть города
 */
export type PlaceKind = 'country' | 'admin1' | 'admin2' | 'city' | 'district';

export type Place = {
  /** Стабильный ключ вида «ru-msk-cao». Не меняется при переводе. */
  id: string;
  /** ISO 3166-1 alpha-2 страны, которой принадлежит место. */
  countryCode: string;
  /** null для корня страны. */
  parentId: string | null;
  kind: PlaceKind;
  /** Глубина: 0 — страна, 1 — admin1 и так далее. */
  depth: number;
  /**
   * Название на языке страны — то, что написано на дорожном знаке.
   * Это основная форма, она всегда есть.
   */
  name: string;
  /**
   * Переводы и альтернативные написания: München → Munich, Мюнхен.
   * Нужны и для показа, и для поиска: человек ищет на своём языке.
   */
  names?: Record<string, string>;
  /** Исторические и разговорные варианты для поиска: «Питер», «NYC», «Bombay». */
  aliases?: string[];
  /** Широта и долгота центра. Без них не работают радиус и «рядом со мной». */
  lat?: number;
  lon?: number;
  /**
   * Путь предков от страны до родителя включительно.
   * Даёт проверку вложенности за одно сравнение вместо обхода дерева:
   * поиск по стране находит всё внутри неё.
   */
  path: string[];
};

/**
 * Подписи уровней для конкретной страны.
 * Ключ — язык, значение — как называть уровень на этом языке.
 *
 * Для России admin1 по-русски «Регион», по-английски «Region».
 * Для США admin1 по-английски «State», по-русски «Штат».
 * Механический перевод здесь не работает: «область» и «state» — не синонимы.
 */
export type LevelLabels = Record<string, string[]>;

export type PlaceTree = {
  countryCode: string;
  /**
   * Сколько уровней реально используется в этой стране.
   * Сингапур — 2, Россия — 4. Интерфейс строит столько шагов выбора,
   * сколько объявлено здесь.
   */
  depth: number;
  /** Подписи уровней по языкам. Обязателен хотя бы один язык. */
  levelLabels: LevelLabels;
  places: Place[];
};

/** Выбранное пользователем место плюс радиус поиска. */
export type LocationSelection = {
  /** id места. null — «вся страна». */
  placeId: string | null;
  /** Радиус в километрах. 0 или undefined — искать по границам места. */
  radiusKm?: number;
  /** Точка, от которой считается радиус, если она отличается от центра места. */
  lat?: number;
  lon?: number;
};

/** Место, к которому привязано объявление. */
export type ItemLocation = {
  placeId: string;
  /** Координаты объекта. Нужны для радиуса: центр города тут не годится. */
  lat?: number;
  lon?: number;
};

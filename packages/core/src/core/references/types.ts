/**
 * Справочники значений.
 *
 * Проблема, которую они решают. Варианты для полей вроде «Марка» лежали прямо
 * в конфигурации категории. Для девяти марок это работало, для полутора сотен
 * уже нет, а модели туда не помещаются вовсе: у одной Toyota их полсотни,
 * и они зависят от выбранной марки.
 *
 * Справочник — это отдельный набор значений со своей структурой, который
 * грузится по требованию. Поле ссылается на него по имени.
 *
 * Три вещи, ради которых он устроен именно так:
 *
 * 1. Иерархия. Модель принадлежит марке, порода — виду животного, район —
 *    городу. Связка «выбрал марку → показались её модели» работает через
 *    parentId, без единого условия в коде категории.
 *
 * 2. Ленивая загрузка. Полный справочник авто — тысячи записей. Он не должен
 *    попадать в бандл человека, который зашёл продать диван.
 *
 * 3. Автономность. Сломанный или недогрузившийся справочник не должен ронять
 *    форму. Поле в этом случае превращается в обычный ввод текста: человек
 *    впишет марку руками, а не упрётся в пустой список.
 */

export type ReferenceEntry = {
  /** Стабильный ключ. Не меняется при переводе и переименовании. */
  id: string;
  /** Значение для показа и хранения в объявлении. */
  name: string;
  /** Родитель внутри этого же справочника: модель → марка. */
  parentId?: string;
  /** Переводы названия по языкам, если оно переводится. */
  names?: Record<string, string>;
  /** Альтернативные написания для поиска: «Мерседес», «Мерс». */
  aliases?: string[];
  /** Популярные показываются первыми — так человек чаще находит без поиска. */
  popular?: boolean;
};

export type ReferenceSet = {
  /** Имя справочника: 'auto-brands', 'pet-breeds'. */
  id: string;
  /**
   * Сколько уровней. 1 — плоский список (цвета), 2 — марка и модель,
   * 3 — марка, модель, поколение.
   */
  depth: number;
  entries: ReferenceEntry[];
};

/** Состояние справочника в реестре. */
export type ReferenceStatus = 'ok' | 'loading' | 'failed' | 'absent';

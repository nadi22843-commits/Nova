import { FavoriteButton } from '../../features/favorites/components/FavoriteButton';

/**
 * Избранное в карточках категорий.
 *
 * Правило доступа Nova: гость может добавлять в избранное без входа.
 * Раньше обёртка отправляла гостя на вход, а вместо сердечка рисовала
 * неоформленную кнопку (класса favorite-button нет в стилях).
 *
 * Избранное хранится локально (FavoritesStore) и переживает перезапуск,
 * поэтому причина закрывать его авторизацией исчезла. Имя компонента
 * оставлено, чтобы не трогать места использования.
 */
export function GuardedFavorite({ id }: { id: string }) {
  return <FavoriteButton id={id} />;
}
